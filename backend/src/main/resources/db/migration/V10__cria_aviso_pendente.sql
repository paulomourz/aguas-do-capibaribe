-- V10: aviso de alerta que o Telegram não recebeu.
-- A API tenta enviar o aviso até 3 vezes. Se todas falharem (erro de rede, Telegram fora do ar ou
-- recusando), o aviso fica registrado aqui como pendente, em vez de existir só no log.
-- Uma linha por alerta. ultimo_erro guarda só o tipo do erro ou o status HTTP, nunca o token do bot.

CREATE TABLE aviso_pendente (
    id          integer                  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    alerta_id   integer                  NOT NULL,
    tentativas  integer                  NOT NULL,
    ultimo_erro character varying(60)    NOT NULL,
    criado_em   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT aviso_pendente_pkey PRIMARY KEY (id),
    CONSTRAINT aviso_pendente_alerta_id_key UNIQUE (alerta_id),
    CONSTRAINT aviso_pendente_alerta_id_fkey FOREIGN KEY (alerta_id) REFERENCES alerta (id),
    CONSTRAINT aviso_pendente_tentativas_check CHECK (tentativas >= 1)
);

-- Usuário da API (se já existir): só lê e insere.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aguas_api') THEN
        GRANT SELECT, INSERT ON aviso_pendente TO aguas_api;
        GRANT USAGE, SELECT ON SEQUENCE aviso_pendente_id_seq TO aguas_api;
    END IF;
END;
$$;
