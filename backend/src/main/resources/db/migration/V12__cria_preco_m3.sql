-- V12: preço do m³ da água comprada (poço e caminhão-pipa juntos), base do custo da água.
-- Cada preço vale a partir de "vigencia" até outro com vigência maior. Na mesma vigência, vale o cadastrado por último:
-- é assim que se corrige um erro de digitação, sem apagar nada.

CREATE TABLE preco_m3 (
    id            integer                  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    valor         numeric(10,2)            NOT NULL,
    vigencia      date                     NOT NULL,
    usuario_id    integer                  NOT NULL,
    cadastrado_em timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT preco_m3_pkey PRIMARY KEY (id),
    CONSTRAINT preco_m3_valor_check CHECK (valor > 0),
    CONSTRAINT preco_m3_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

-- Imutável, como o lote: o histórico de preços é a prova de quem mudou o quê.
CREATE FUNCTION bloquear_alteracao_preco_m3() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    RAISE EXCEPTION 'Preço do m³ não pode ser alterado nem excluído.';
END;
$$;

CREATE TRIGGER trg_preco_m3_imutavel BEFORE DELETE OR UPDATE ON preco_m3
    FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_preco_m3();

-- Usuário da API (se já existir): só lê e insere.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aguas_api') THEN
        GRANT SELECT, INSERT ON preco_m3 TO aguas_api;
        GRANT USAGE, SELECT ON SEQUENCE preco_m3_id_seq TO aguas_api;
    END IF;
END;
$$;
