-- V4: auditoria das ações do gestor sobre outros usuários (issue #16; antes database/migracoes/001).
-- Registro imutável e sem coluna de senha.

-- Imutável, como o lote: auditoria que pode ser apagada não prova nada.
CREATE FUNCTION bloquear_alteracao_auditoria() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    RAISE EXCEPTION 'Registro de auditoria não pode ser alterado nem excluído.';
END;
$$;

-- Quem (gestor_id) fez o quê (acao) com quem (usuario_afetado_id) e quando (data_hora).
-- Não há coluna de senha: nem a nova senha nem o hash são guardados aqui.
CREATE TABLE auditoria_usuario (
    id                 integer                  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    gestor_id          integer                  NOT NULL,
    usuario_afetado_id integer                  NOT NULL,
    acao               character varying(30)    NOT NULL,
    data_hora          timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT auditoria_usuario_pkey PRIMARY KEY (id),
    CONSTRAINT auditoria_usuario_acao_check
        CHECK ((acao)::text = ANY ((ARRAY['REDEFINICAO_SENHA'::character varying, 'DESATIVACAO_USUARIO'::character varying, 'REATIVACAO_USUARIO'::character varying])::text[])),
    CONSTRAINT auditoria_usuario_gestor_id_fkey FOREIGN KEY (gestor_id) REFERENCES usuario (id),
    CONSTRAINT auditoria_usuario_usuario_afetado_id_fkey FOREIGN KEY (usuario_afetado_id) REFERENCES usuario (id)
);

CREATE INDEX auditoria_usuario_afetado_idx ON auditoria_usuario USING btree (usuario_afetado_id, data_hora);

CREATE TRIGGER trg_auditoria_imutavel BEFORE DELETE OR UPDATE ON auditoria_usuario
    FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_auditoria();

-- Usuário da API (se já existir): só lê e insere; nunca altera nem apaga.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aguas_api') THEN
        GRANT SELECT, INSERT ON auditoria_usuario TO aguas_api;
        GRANT USAGE, SELECT ON SEQUENCE auditoria_usuario_id_seq TO aguas_api;
    END IF;
END;
$$;
