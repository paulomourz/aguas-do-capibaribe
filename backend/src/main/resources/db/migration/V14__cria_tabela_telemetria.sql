-- V14: leituras de telemetria do sensor (issues #157 e #158).
-- Cada POST /telemetria grava uma linha: a vazão medida pelo ESP32 (Wokwi) num processo de lavagem.
-- É histórico de medição: como o lote, não se altera nem se apaga. O aguas_api só lê e insere.
-- A hora da última leitura mostra se o sensor está enviando (indicador de saúde, issue #158).

CREATE TABLE telemetria (
    id            integer                  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    processo_id   integer                  NOT NULL,
    usuario_id    integer                  NOT NULL,
    vazao_litros  numeric(7,2)             NOT NULL,
    registrado_em timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT telemetria_pkey PRIMARY KEY (id),
    CONSTRAINT telemetria_processo_id_fkey FOREIGN KEY (processo_id) REFERENCES processo (id),
    CONSTRAINT telemetria_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT telemetria_vazao_litros_check CHECK (vazao_litros BETWEEN 0 AND 10000)
);

-- Última leitura de cada processo (indicador de saúde) e consultas por processo e período.
CREATE INDEX ix_telemetria_processo_data ON telemetria USING btree (processo_id, registrado_em DESC);
-- Última leitura de todas (indicador de saúde) e consultas só por período.
CREATE INDEX ix_telemetria_data ON telemetria USING btree (registrado_em DESC);
-- Chave estrangeira do usuário: sem índice, desativar ou apagar um usuário leria a tabela inteira.
CREATE INDEX ix_telemetria_usuario ON telemetria USING btree (usuario_id);

-- Tabela que só recebe INSERT e cresce rápido (uma leitura a cada poucos segundos): mesmos ajustes da V13.
ALTER TABLE telemetria SET (
    autovacuum_vacuum_scale_factor = 0.05,
    autovacuum_vacuum_insert_scale_factor = 0.05,
    autovacuum_analyze_scale_factor = 0.02
);

-- Usuário da API (se já existir): só lê e insere.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aguas_api') THEN
        GRANT SELECT, INSERT ON telemetria TO aguas_api;
        GRANT USAGE, SELECT ON SEQUENCE telemetria_id_seq TO aguas_api;
    END IF;
END;
$$;
