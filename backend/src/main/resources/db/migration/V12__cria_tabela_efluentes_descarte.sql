-- V12: auditoria do descarte de efluentes de cada lote (issue #162).
-- Rastreabilidade pedida pela CPRH e pela ISO 14001: para cada descarte, o volume, o pH, a turbidez e quanto
-- da água foi reaproveitado. Um lote pode ter mais de um descarte (um por etapa ou por tanque).
-- É registro de auditoria: como o lote, não se altera nem se apaga. O aguas_api só lê e insere.

CREATE TABLE efluentes_descarte (
    id                     integer                  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    lote_id                integer                  NOT NULL,
    data_descarte          timestamp with time zone NOT NULL DEFAULT now(),
    volume_litros          numeric(12,2)            NOT NULL,
    ph                     numeric(4,2)             NOT NULL,
    turbidez_ntu           numeric(10,2)            NOT NULL,
    reutilizado_percentual numeric(5,2)             NOT NULL DEFAULT 0,
    CONSTRAINT efluentes_descarte_pkey PRIMARY KEY (id),
    CONSTRAINT efluentes_descarte_lote_id_fkey FOREIGN KEY (lote_id) REFERENCES lote (id),
    CONSTRAINT efluentes_descarte_volume_litros_check CHECK (volume_litros > 0),
    CONSTRAINT efluentes_descarte_ph_check CHECK (ph BETWEEN 0 AND 14),
    CONSTRAINT efluentes_descarte_turbidez_ntu_check CHECK (turbidez_ntu >= 0),
    CONSTRAINT efluentes_descarte_reutilizado_percentual_check CHECK (reutilizado_percentual BETWEEN 0 AND 100)
);

-- Descartes de um lote (e a chave estrangeira: sem ele, cada verificação de lote leria a tabela inteira).
CREATE INDEX ix_efluentes_descarte_lote ON efluentes_descarte USING btree (lote_id);
-- Relatório de conformidade por período, do mais recente ao mais antigo.
CREATE INDEX ix_efluentes_descarte_data ON efluentes_descarte USING btree (data_descarte DESC);

-- Usuário da API (se já existir): só lê e insere. Sem UPDATE nem DELETE: a linha é a prova do descarte.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aguas_api') THEN
        GRANT SELECT, INSERT ON efluentes_descarte TO aguas_api;
        GRANT USAGE, SELECT ON SEQUENCE efluentes_descarte_id_seq TO aguas_api;
    END IF;
END;
$$;
